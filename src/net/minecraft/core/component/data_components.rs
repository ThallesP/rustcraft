#[cfg(test)]
mod tests {
    use super::TYPES;
    use crate::golden::Golden;

    #[test]
    fn matches_vanilla() {
        let golden = Golden::load("net.minecraft.core.component.DataComponents");
        golden.field(
            "TYPES",
            TYPES
                .iter()
                .map(|(name, transient)| (format!("minecraft:{name}"), *transient))
                .collect::<Vec<_>>(),
        );
        golden.finish();
    }
}
